#if canImport(CryptoKit)
  import CryptoKit
  package import Foundation
  import Yams

  /// Generates Swift source that keeps secret literals encrypted with ChaChaPoly and decrypts them with CryptoKit at
  /// runtime, from a swift-confidential configuration file.
  ///
  /// The generated source needs no package dependency. Each secret's key and nonce derive from its name and value, so
  /// the same configuration always produces the same source.
  package enum CryptoKitSecretsGenerator {
    /// Returns the generated Swift source for a swift-confidential YAML configuration.
    ///
    /// Reads `secrets` (`name`, `value` as a string or a list of strings, optional `accessModifier` and `namespace`),
    /// `defaultAccessModifier` and `defaultNamespace`; the obfuscation `algorithm` keys are ignored.
    ///
    /// - Parameter configurationData: The YAML configuration, with environment variables already substituted.
    /// - Returns: Swift source declaring one accessor per secret.
    /// - Throws: An error if the configuration can't be decoded or declares an invalid name or namespace.
    package static func generate(configurationData: Data) throws -> String {
      let configuration = try YAMLDecoder().decode(Configuration.self, from: configurationData)
      var namespaces: [Namespace] = []
      for secret in configuration.secrets {
        let namespace = try Namespace(
          secret.namespace ?? configuration.defaultNamespace ?? Namespace.defaultDeclaration
        )
        let accessModifier = secret.accessModifier ?? configuration.defaultAccessModifier ?? "internal"
        let member = try accessor(for: secret, accessModifier: accessModifier)
        if let index = namespaces.firstIndex(where: { $0.declaration == namespace.declaration }) {
          namespaces[index].members.append(member)
        } else {
          var namespace = namespace
          namespace.members = [member]
          namespaces.append(namespace)
        }
      }

      let imports = Set(namespaces.compactMap(\.module)).sorted()
      var lines = ["// Generated by mpct. Do not edit.", "", "import CryptoKit", "import Foundation"]
      lines += imports.map { "import \($0)" }
      for namespace in namespaces {
        lines += ["", namespace.opening]
        lines += namespace.members.joined(separator: "\n\n").split(separator: "\n", omittingEmptySubsequences: false)
          .map { $0.isEmpty ? "" : "    \($0)" }
        lines.append("}")
      }
      lines += ["", runtimeSupport]
      return lines.joined(separator: "\n") + "\n"
    }

    /// Encrypts `payload` with a key and nonce derived from `name` and `payload`.
    ///
    /// - Returns: The key bytes and the sealed box in its combined form (nonce, ciphertext, tag).
    static func seal(_ payload: Data, name: String) throws -> (key: [UInt8], box: [UInt8]) {
      let material = Data(name.utf8) + Data([0]) + payload
      let key = SymmetricKey(data: SHA256.hash(data: Data("mpct.secrets.key".utf8) + material))
      let nonce = try ChaChaPoly.Nonce(data: Array(SHA256.hash(data: Data("mpct.secrets.nonce".utf8) + material)).prefix(12))
      let box = try ChaChaPoly.seal(payload, using: key, nonce: nonce)
      return (key.withUnsafeBytes { Array($0) }, Array(box.combined))
    }

    private static func accessor(for secret: Configuration.Secret, accessModifier: String) throws -> String {
      guard secret.name.isSwiftIdentifier else {
        throw GeneratorError(#"Secret name "\#(secret.name)" isn't a Swift identifier"#)
      }
      let (type, function, payload): (String, String, Data) =
        switch secret.value {
        case let .string(value): ("String", "string", Data(value.utf8))
        case let .strings(values): ("[String]", "strings", try JSONEncoder().encode(values))
        }
      let sealed = try seal(payload, name: secret.name)
      return """
        \(accessModifier) static var \(secret.name): \(type) {
            _MPCTSecrets.\(function)(
                key: \(byteArray(sealed.key, indent: 8)),
                box: \(byteArray(sealed.box, indent: 8))
            )
        }
        """
    }

    private static func byteArray(_ bytes: [UInt8], indent: Int) -> String {
      let rows = stride(from: 0, to: bytes.count, by: 16).map { start in
        bytes[start..<min(start + 16, bytes.count)].map { String(format: "0x%02x", $0) }.joined(separator: ", ")
      }
      let pad = String(repeating: " ", count: indent + 4)
      return "[\n" + rows.map { pad + $0 }.joined(separator: ",\n") + "\n" + String(repeating: " ", count: indent) + "]"
    }

    private static let runtimeSupport = """
      private enum _MPCTSecrets {
          static func string(key: [UInt8], box: [UInt8]) -> String {
              String(decoding: open(key: key, box: box), as: UTF8.self)
          }

          static func strings(key: [UInt8], box: [UInt8]) -> [String] {
              do {
                  return try JSONDecoder().decode([String].self, from: open(key: key, box: box))
              } catch {
                  preconditionFailure("A generated secret holds no string list: \\(error)")
              }
          }

          private static func open(key: [UInt8], box: [UInt8]) -> Data {
              do {
                  return try ChaChaPoly.open(ChaChaPoly.SealedBox(combined: box), using: SymmetricKey(data: key))
              } catch {
                  preconditionFailure("A generated secret failed to decrypt: \\(error)")
              }
          }
      }
      """
  }

  extension CryptoKitSecretsGenerator {
    struct GeneratorError: Swift.Error, CustomStringConvertible {
      let description: String
      init(_ description: String) { self.description = description }
    }

    struct Configuration: Decodable {
      var defaultAccessModifier: String?
      var defaultNamespace: String?
      var secrets: [Secret]

      struct Secret: Decodable {
        var name: String
        var value: Value
        var accessModifier: String?
        var namespace: String?
      }

      enum Value: Decodable {
        case string(String)
        case strings([String])

        init(from decoder: any Decoder) throws {
          let container = try decoder.singleValueContainer()
          if let value = try? container.decode(String.self) {
            self = .string(value)
          } else {
            self = .strings(try container.decode([String].self))
          }
        }
      }
    }

    /// A swift-confidential namespace: `create Name`, `extend Name` or `extend Name from Module`.
    struct Namespace {
      static let defaultDeclaration = "create ObfuscatedLiterals"

      let declaration: String
      let opening: String
      let module: String?
      var members: [String] = []

      init(_ declaration: String) throws {
        let words = declaration.split(separator: " ").map(String.init)
        let isNameValid: (String) -> Bool = { $0.split(separator: ".").allSatisfy { String($0).isSwiftIdentifier } }
        switch words.count {
        case 2 where words[0] == "create" && words[1].isSwiftIdentifier:
          opening = "enum \(words[1]) {"
          module = nil
        case 2 where words[0] == "extend" && isNameValid(words[1]):
          opening = "extension \(words[1]) {"
          module = nil
        case 4 where words[0] == "extend" && isNameValid(words[1]) && words[2] == "from" && words[3].isSwiftIdentifier:
          opening = "extension \(words[1]) {"
          module = words[3]
        default:
          throw GeneratorError(#"Namespace "\#(declaration)" isn't "create Name", "extend Name" or "extend Name from Module""#)
        }
        self.declaration = declaration
      }
    }
  }

  extension String {
    fileprivate var isSwiftIdentifier: Bool {
      guard let first = unicodeScalars.first, first == "_" || CharacterSet.letters.contains(first) else { return false }
      return unicodeScalars.allSatisfy { $0 == "_" || CharacterSet.alphanumerics.contains($0) }
    }
  }
#endif
